"""Generate the exact integer square-root mantissa table (no float math)."""

from math import isqrt
from pathlib import Path

values = [isqrt(128 * (m + 1) - 1) for m in range(128, 512)]
destination = Path(__file__).resolve().parents[1] / "src/bf16/sqrt-table.inc"
lines = ["# Generated by mytests/generate_bf16_table.py; m = 128..511."]
for offset in range(0, len(values), 16):
    lines.append("    .byte " + ", ".join(map(str, values[offset:offset + 16])))
destination.write_text("\n".join(lines) + "\n", encoding="ascii")
